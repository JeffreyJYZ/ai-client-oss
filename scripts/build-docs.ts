/**
 * Generates the plugin API reference the `/docs` page renders.
 *
 * It extracts the public surface from the modules the app actually ships (see
 * `web/src/docs/entries.ts` for the entry list) and writes it to
 * `web/src/docs/reference.generated.ts`, which `web/src/docs/reference.test.ts`
 * then holds to the source. Nothing in the output is hand-written: every
 * export, the slot map, the manifest fields and the event names are read out of
 * the source text, so the page cannot drift from the API.
 *
 * Run from `web/`: `bun run docs`. `web/package.json`'s `build` runs it first,
 * so a deploy can never ship a stale reference. A module that does not exist yet
 * is recorded as `pending`, never an error — several Phase 2 seams land after
 * this script does, and the docs build must not break the app's deploy.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { buildReference } from "../web/src/docs/build";

const webRoot = fileURLToPath(new URL("../web", import.meta.url));

const read = (path: string): string | null => {
	const full = join(webRoot, path);
	return existsSync(full) ? readFileSync(full, "utf8") : null;
};

const exists = (path: string): boolean => existsSync(join(webRoot, path));

const readAppVersion = (): string => {
	const pkg = read("package.json");
	if (pkg === null) return "";
	const parsed: unknown = JSON.parse(pkg);
	if (
		typeof parsed === "object" &&
		parsed !== null &&
		"version" in parsed &&
		typeof parsed.version === "string"
	) {
		return parsed.version;
	}
	return "";
};

const reference = buildReference({ read, exists, appVersion: readAppVersion() });

const header = [
	"// GENERATED by `bun run docs` (from web/) — do not edit by hand.",
	"// Every value below is extracted from the shipped source; the entry list is",
	"// src/docs/entries.ts and the coverage gate is src/docs/reference.test.ts.",
	'import type { DocReference } from "@/docs/types";',
	"",
];

const contents = `${header.join("\n")}export const reference: DocReference = ${JSON.stringify(
	reference,
	null,
	"\t",
)};\n`;

const target = join(webRoot, "src/docs/reference.generated.ts");
const previous = existsSync(target) ? readFileSync(target, "utf8") : null;

if (previous === contents) {
	process.stdout.write("docs: reference already current\n");
} else {
	writeFileSync(target, contents);
	process.stdout.write("docs: wrote src/docs/reference.generated.ts\n");
}

const documented = reference.modules.filter(
	(module) => module.status === "documented",
);
const symbols = documented.reduce(
	(total, module) => total + module.symbols.length,
	0,
);
process.stdout.write(
	`docs: ${documented.length} documented module(s), ${symbols} exported symbol(s), api ${reference.apiVersion}\n`,
);
if (reference.pending.length > 0) {
	process.stdout.write(
		`docs: pending (no source yet, named on the page): ${reference.pending.join(", ")}\n`,
	);
}
process.stdout.write(
	`docs: ${reference.slots.length} slots, ${reference.manifestFields.length} manifest fields, ${reference.capabilities.length} capabilities, ${reference.events.length} events\n`,
);
